"""Generate offline double-pinyin resources from pinned Rime Ice mappings.

Only the syllable keyboard mappings are reused, not the upstream UI/Lua stack.
English dictionary codes use private-use letters until the final algebra step,
so e.g. logo is not accidentally converted as if it were a Chinese syllable.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESOURCES = ROOT / 'Resources'
layouts = json.loads((ROOT / 'scripts/double-pinyin-layouts.json').read_text())
names = {'sogou': '搜狗双拼', 'flypy': '小鹤双拼', 'natural': '自然码',
         'microsoft': '微软双拼', 'abc': '智能 ABC', 'jiajia': '拼音加加', 'ziguang': '紫光双拼'}
alphabet = 'abcdefghijklmnopqrstuvwxyz'
protected = ''.join(chr(0xE000 + i) for i in range(26))
mapping = str.maketrans(alphabet, protected)
english = (RESOURCES / 'mixed_english.dict.yaml').read_text().split('...\n', 1)[1]
rows = []
for line in english.splitlines():
    if not line or line.startswith('#'):
        continue
    parts = line.split('\t')
    parts[1] = parts[1].translate(mapping)
    rows.append('\t'.join(parts))
(RESOURCES / 'fangcun_english.dict.yaml').write_text(
    '# Generated by scripts/prepare-double-pinyin.py from mixed_english.dict.yaml.\n'
    '# See RIMEICE-LICENSE.txt. Private-use spellings preserve literal English.\n'
    '---\nname: fangcun_english\nversion: "1.0"\nsort: by_weight\n...\n' + '\n'.join(rows) + '\n')
(RESOURCES / 'fangcun_double.dict.yaml').write_text(
    '---\nname: fangcun_double\nversion: "1.0"\nsort: by_weight\n'
    'import_tables:\n  - pinyin_simp\n  - base\n  - fangcun_english\n...\n')
base = (RESOURCES / 'translate_type.schema.yaml').read_text()
for key, layout in layouts.items():
    schema = 'fangcun_' + key
    rules = layout['algebra'] + [f'xlit/{protected}/{alphabet}/',
                                r'derive/^([a-z;]+)$/\U$1/', r'derive/^([a-z])/\U$1/']
    speller = ('speller:\n  alphabet: abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ;\n'
               '  initials: abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ\n'
               '  delimiter: " \'"\n  algebra:\n' +
               ''.join('    - ' + json.dumps(rule, ensure_ascii=False) + '\n' for rule in rules))
    translator = (f'translator:\n  dictionary: fangcun_double\n  prism: {schema}\n'
                  '  user_dict: fangcun_double\n  enable_user_dict: true\n')
    text = re.sub(r'(?ms)^schema:.*?(?=^switches:)',
                  f'schema:\n  schema_id: {schema}\n  name: 方寸{names[key]}\n  version: "1.0"\n', base)
    text = re.sub(r'(?ms)^speller:.*?(?=^translator:)', lambda _: speller, text)
    text = re.sub(r'(?ms)^translator:.*?(?=^menu:)', lambda _: translator, text)
    header = (f'# Generated by scripts/prepare-double-pinyin.py.\n'
              f'# Keyboard mapping: iDvel/rime-ice/{layout["source"]}\n'
              f'# Revision: {layout["revision"]}; see RIMEICE-LICENSE.txt.\n')
    (RESOURCES / (schema + '.schema.yaml')).write_text(header + text)
(RESOURCES / 'default.yaml').write_text('config_version: "1.1"\nschema_list:\n'
    '  - schema: translate_type\n' + ''.join(f'  - schema: fangcun_{key}\n' for key in layouts)
    + 'menu:\n  page_size: 5\n')
print('已生成七种双拼方案及保留英文原码的混输词库。')
